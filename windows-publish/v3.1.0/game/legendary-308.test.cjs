'use strict';
// v3.0.8 real combat VM regression (the same scripts the multiplayer server runs).
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const names=['equipment','world','navigation','presentation','game','loadout','accessories','weapons','combat-feel','battle-scale','weapon-identity','compact-draft','targeting','spell-catalog','catalog-weapons','catalog-expansion','weapon-variants-core','combat-tactics','tactical-abilities','support-role','objectives','maps','lanes','spell-art','expansion','deathmatch','potions','combat-balance','multiplayer-rules','arena-update','gear-v3','gear-v4','gear-v5','relic-maze','balance-v6','legendary-weapons-308'];
const draw=new Proxy({},{get:(o,k)=>o[k]||(()=>({addColorStop(){}}))});
const els=new Map();
function el(k){if(!els.has(k))els.set(k,{style:{},dataset:{},classList:{add(){},remove(){},toggle(){}},getBoundingClientRect:()=>({width:950,height:650}),getContext:()=>draw,addEventListener(){},focus(){},textContent:'',innerHTML:''});return els.get(k);}
const box={document:{querySelector:el,querySelectorAll:()=>[]},window:{addEventListener(){}},ResizeObserver:class{observe(){}},requestAnimationFrame(){},devicePixelRatio:1,Math,console};
vm.createContext(box);
for(const n of names)vm.runInContext(fs.readFileSync(__dirname+'/dist/'+n+'.js','utf8'),box,{filename:n+'.js'});
const run=src=>vm.runInContext(src,box);
const setup=(weapon,option=0)=>{
 run(`phase='fight';paused=false;matchType='vs';clock=180;round=1;actors=[actor(0,0,0,'blade',true),actor(1,95,0,'blade',true),actor(1,125,10,'blade',true),actor(0,95,-25,'blade',true)];shots=[];zones=[];effects=[];floating=[];for(const a of actors){applyGear(a,{head:0,armor:0,boots:0,main:a.team===0?'sword':'sword',off:-1});a.invul=0;a.stun=0;a.control={mouse:{x:100,y:0},target:null,enemy:null};a.ai=999;}applyGear(actors[0],{head:0,armor:0,boots:0,main:${JSON.stringify(weapon)},off:-1});actors[0].loadout=[${option},0,0,0];actors[0].ai=999;actors[0].control={mouse:{x:95,y:0},target:null,enemy:null};`);
};
// Test real weapon timers in isolation from baseline AI attacks.
const advance=(seconds)=>{for(let i=0;i<Math.round(seconds/.05);i++)run('kh308Step(.05)');};
for(const [id,hp] of [['twinaxe',2600],['legendshield',2550]]){
 assert.equal(run('weaponBook.'+id+'.kind'),'blade');
 assert.equal(run('weaponBook.'+id+'.hands'),2);
 assert.equal(run(`weaponPair('${id}','sword')`),false,'new main weapon consumes both equipment slots');
 setup(id);
 assert.ok(Math.abs(run('actors[0].max')-hp)<200,'weapon base HP must reflect requested budget');
 assert.equal(run('actors[0].hp'),run('actors[0].max'));
 assert.ok(run('validGear({head:0,armor:0,boots:0,main:'+JSON.stringify(id)+',off:-1})'));
}
setup('twinaxe',0);
const before=run('actors[1].hp');
assert.equal(run('cast(actors[0],0,{x:120,y:0})'),true);
assert.ok(run('actors[0].cd[0]>=10.9'));
advance(.85);
assert.equal(run('actors[1].hp'),before,'line damage waits for channel completion');
advance(.3);
assert.ok(run('actors[1].hp')<before,'channel deals line damage');
assert.ok(run('actors[1].stun')>1,'line hit stuns enemy');
assert.equal(run('actors[3].hp'),run('actors[3].max'),'friendly player not stunned by line');
setup('twinaxe',0);
assert.equal(run('cast(actors[0],0,{x:120,y:0})'),true);
run('actors[0].stun=2');
advance(.15);
assert.equal(run('actors[0].kh308Channel'),null,'stun interrupts focus');
assert.ok(run('actors[0].cd[0]>0'),'interrupted cast retains cooldown');
setup('twinaxe',1);
run('actors[0].control.mouse={x:110,y:0}');
assert.equal(run('cast(actors[0],0,{x:110,y:0})'),true);
const axeBefore=run('actors[1].hp');
advance(2.95);
assert.ok(run('actors[1].hp')<axeBefore,'three-second spinning area ticks damage');
assert.ok(run('actors[0].cd[0]>0'),'spin starts 9-second cooldown');
setup('legendshield',0);
assert.equal(run('cast(actors[0],0,{x:90,y:0})'),true);
advance(1.8);
assert.equal(run('actors[0].kh308Guard'),0,'no shield reduction before channel finishes');
advance(.3);
assert.equal(run('actors[0].kh308Guard'),.70,'successful Q1 grants 70% reduction');
const auraBefore=run('actors[1].hp');
advance(1.05);
assert.ok(run('actors[1].hp')<auraBefore,'aura deals 90 per second');
run('actors[0].stun=1.2');
advance(.05);
assert.equal(run('actors[0].kh308Guard'),0,'stun immediately cancels aura protection');
assert.equal(run('actors[0].kh308Aura'),null,'aura stops on stun');
setup('legendshield',1);
assert.equal(run('cast(actors[0],0,{x:300,y:0})'),true);
const ramBefore=run('actors[1].hp'),friendBefore=run('actors[3].x');
advance(2.5);
assert.ok(run('actors[1].hp')<ramBefore,'ram collision hits enemy');
assert.ok(run('actors[3].x')!==friendBefore||run('actors[3].y')!==-25,'ram pushes friendly characters too');
assert.ok(run('actors[0].x')>170,'ram moves forward over 2.5 seconds');
assert.equal(run('actors[0].kh308Guard'),0,'rush protection stops after dash');
const html=fs.readFileSync(__dirname+'/dist/index.html','utf8');
const server=fs.readFileSync(__dirname+'/server.cjs','utf8');
assert.match(html,/src="legendary-weapons-308\.js"/);
assert.match(html,/src="legendary-weapon-art-308\.js"/);
assert.match(server,/'balance-v6','legendary-weapons-308'/);
const art=fs.readFileSync(__dirname+'/dist/legendary-weapon-art-308.js','utf8');
assert.match(art,/drawChampion=function\(a\)/);
assert.match(art,/weaponVariantSvg=function/);
assert.match(art,/equipmentIcon=function/);
console.log('PASS: v3.0.8 twin axe, epic shield, channels, stun, DOT, rush, mitigation and original artwork routing');
